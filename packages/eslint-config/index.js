// @ts-check
import { execFileSync } from 'node:child_process'
import antfu from '@antfu/eslint-config'
import drupal from '@ueberbit/eslint-config-drupal'
import { defu } from 'defu'

/**
 * @template T
 * @typedef {T | Promise<T>} Awaitable
 */

/**
 * @typedef {import('@antfu/eslint-config').ConfigNames} AntfuConfigNames
 * @typedef {'ueberbit/drupal'} CustomConfigNames
 * @typedef {AntfuConfigNames | CustomConfigNames} ConfigNames
 * @typedef {import('@antfu/eslint-config').OptionsConfig} OptionsConfig
 * @typedef {import('@antfu/eslint-config').TypedFlatConfigItem} TypedFlatConfigItem
 * @typedef {Parameters<typeof antfu>} antfuParams
 */

/**
 * Every .gitignore below the cwd that Git applies, nested ones included.
 * eslint-config-flat-gitignore only reads the nearest one by default. Asking
 * Git skips ignored directories (vendor, web/core) instead of walking them.
 *
 * @returns {OptionsConfig['gitignore']}
 *  Options for eslint-config-flat-gitignore, or `true` outside a Git repo.
 */
function gitignore() {
  try {
    const files = execFileSync(
      'git',
      [
        'ls-files',
        '-z',
        '--cached',
        '--others',
        '--exclude-standard',
        '--',
        ':(glob)**/.gitignore',
      ],
      {
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      },
    ).split('\0').filter(Boolean)
    return files.length
      ? { files, strict: false }
      : true
  }
  catch {
    return true
  }
}

/**
 * Construct an array of ESLint flat config items.
 *
 * @param {OptionsConfig & TypedFlatConfigItem} options
 *  The options for generating the ESLint configurations.
 * @param {Awaitable<TypedFlatConfigItem | TypedFlatConfigItem[]>[]} userConfigs
 *  The user configurations to be merged with the generated configurations.
 * @returns {ReturnType<import('@antfu/eslint-config').antfu>}
 *  The merged ESLint configurations.
 */
function config(options = {}, ...userConfigs) {
  return antfu(defu(options, /** @type {OptionsConfig} */ {
    gitignore: gitignore(),
  }), ...userConfigs)
    .append(drupal())
    .append({
      ignores: [
        'tsconfig.json',
        '.vscode/**/*',
        'composer.json',
        'composer.lock',
        '**/.storybook/**',
        '**/*.jsx',
        '**/_deprecated/**',
        // Generated by @ueberbit/vite-plugin-drupal.
        '**/.uebertool/**',
      ],
    })
}
export default config
